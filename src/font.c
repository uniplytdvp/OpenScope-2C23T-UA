const uint8_t *font5x7_get_codepoint(uint16_t cp) {
    if (cp >= 'a' && cp <= 'z') {
        if (cp != 'm' && cp != 'n') {
            cp = (uint16_t)(cp - ('a' - 'A'));
        }
    } else if (cp >= 0x0430 && cp <= 0x044F) {
        cp = (uint16_t)(cp - 0x20); // Cyrillic lowercase to uppercase
    } else if (cp == 0x0491) {
        cp = 0x0490; // ґ -> Ґ
    } else if (cp == 0x0454) {
        cp = 0x0404; // є -> Є
    } else if (cp == 0x0456) {
        cp = 0x0406; // і -> І
    } else if (cp == 0x0457) {
        cp = 0x0407; // ї -> Ї
    }

    // Map Cyrillic uppercase letters that share Latin glyphs
    switch (cp) {
        case 0x0410: cp = 'A'; break; // А -> A
        case 0x0412: cp = 'B'; break; // В -> B
        case 0x0415: cp = 'E'; break; // Е -> E
        case 0x0406: cp = 'I'; break; // І -> I
        case 0x041A: cp = 'K'; break; // К -> K
        case 0x041C: cp = 'M'; break; // М -> M
        case 0x041D: cp = 'H'; break; // Н -> H
        case 0x041E: cp = 'O'; break; // О -> O
        case 0x0420: cp = 'P'; break; // Р -> P
        case 0x0421: cp = 'C'; break; // С -> C
        case 0x0422: cp = 'T'; break; // Т -> T
        case 0x0425: cp = 'X'; break; // Х -> X
        default: break;
    }

    if (cp < 128) {
        char c = (char)cp;
        for (uint32_t i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); ++i) {
            if (glyphs[i].c == c) {
                return glyphs[i].col;
            }
        }
    } else {
        for (uint32_t i = 0; i < sizeof(cyrillic_glyphs) / sizeof(cyrillic_glyphs[0]); ++i) {
            if (cyrillic_glyphs[i].cp == cp) {
                return cyrillic_glyphs[i].col;
            }
        }
    }

    return glyphs[0].col; // Space / fallback
}

const uint8_t *font5x7_get(char c) {
    return font5x7_get_codepoint((uint8_t)c);
}
